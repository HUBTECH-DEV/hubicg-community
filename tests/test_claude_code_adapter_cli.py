import json
import os
import subprocess
import sys
from pathlib import Path


def run(root: Path, *args: str) -> subprocess.CompletedProcess[str]:
    env = {**os.environ, "PYTHONPATH": str(Path(__file__).parents[1] / "src")}
    return subprocess.run(
        [sys.executable, "-m", "hubicg", "--root", str(root), *args],
        capture_output=True, text=True, env=env, check=False,
    )


def write_role(root: Path, **fields: object) -> None:
    role = {"schemaVersion": "1.0", "instructions": "Be useful.", **fields}
    (root / ".hubicg" / "roles" / f"{role['id']}.json").write_text(json.dumps(role), encoding="utf-8")


def project(tmp_path: Path) -> Path:
    state = tmp_path / ".hubicg"
    (state / "roles").mkdir(parents=True)
    (state / "config.json").write_text(json.dumps({"schemaVersion": "1.0"}), encoding="utf-8")
    write_role(tmp_path, id="one", name="One")
    return tmp_path


def propose_and_apply(root: Path) -> subprocess.CompletedProcess[str]:
    proposal = json.loads(run(root, "--json", "adapters", "claude-code", "propose").stdout)
    return run(root, "adapters", "claude-code", "apply", "--approval", proposal["proposalId"])


def test_diff_is_empty_before_any_export(tmp_path: Path) -> None:
    root = project(tmp_path)
    result = run(root, "--json", "adapters", "claude-code", "diff")
    assert result.returncode == 0
    assert json.loads(result.stdout)["changed"] is True


def test_propose_then_apply_writes_marked_subagent_file(tmp_path: Path) -> None:
    root = project(tmp_path)
    applied = propose_and_apply(root)
    assert applied.returncode == 0
    exported = root / ".hubicg" / "exports" / "claude-code" / "one.md"
    assert exported.is_file()
    assert exported.read_text(encoding="utf-8").startswith("<!-- hubicg:managed role=one ")
    assert "Be useful." in exported.read_text(encoding="utf-8")


def test_diff_is_unchanged_after_apply_with_no_role_changes(tmp_path: Path) -> None:
    root = project(tmp_path)
    propose_and_apply(root)
    result = run(root, "--json", "adapters", "claude-code", "diff")
    assert result.returncode == 0
    assert json.loads(result.stdout) == {"changed": False, "diff": []}


def test_apply_rejects_missing_or_wrong_approval(tmp_path: Path) -> None:
    root = project(tmp_path)
    run(root, "adapters", "claude-code", "propose")
    result = run(root, "adapters", "claude-code", "apply", "--approval", "0" * 16)
    assert result.returncode == 3


def test_propose_rejects_mutually_conflicting_roles(tmp_path: Path) -> None:
    root = project(tmp_path)
    write_role(root, id="two", name="Two", conflictsWith=["one"])
    write_role(root, id="one", name="One", conflictsWith=["two"])
    result = run(root, "adapters", "claude-code", "propose")
    assert result.returncode == 1
    assert "conflicting roles" in result.stderr


def test_apply_never_deletes_a_file_without_the_hubicg_marker(tmp_path: Path) -> None:
    root = project(tmp_path)
    propose_and_apply(root)
    hand_written = root / ".hubicg" / "exports" / "claude-code" / "hand-written.md"
    hand_written.write_text("Not generated by HubICG.\n", encoding="utf-8")
    (root / ".hubicg" / "roles" / "one.json").unlink()
    propose_and_apply(root)
    assert hand_written.is_file()
    assert not (root / ".hubicg" / "exports" / "claude-code" / "one.md").exists()


def test_apply_records_verifiable_change_evidence(tmp_path: Path) -> None:
    root = project(tmp_path)
    propose_and_apply(root)
    result = run(root, "evidence", "changes", "verify")
    assert result.returncode == 0
